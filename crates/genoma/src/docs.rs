//! What Genoma says about itself: `genoma types`, the API as Luau types for
//! luau-lsp, and `genoma reference`, the API reference in Markdown, both
//! from the node schema and `genoma-script/api.luau`.

use std::{fmt::Write as _, path::Path};

use genoma_scene::{PROPS, Ty};
use genoma_script::{API, SERVICES, kit_modules};

/// The node types and the API, as one Luau file.
pub fn definitions() -> String {
    format!("{}\n{}", genoma_scene::luau_definitions(), API)
}

/// `genoma types [dir]`: printed, or written as a directory an alias in
/// `.luaurc` points `@genoma` at: `types.luau`, a module per service typed
/// as it is, and the kit's own sources, so luau-lsp checks every
/// `require("@genoma/…")`.
pub fn types(dir: Option<&Path>) -> std::io::Result<()> {
    let Some(dir) = dir else {
        print!("{}", definitions());
        return Ok(());
    };
    write_types(dir)?;
    println!(
        "Written to {}. In the interface's .luaurc:\n  {{ \"aliases\": {{ \"genoma\": \"{}\" }} }}",
        dir.display(),
        dir.display()
    );
    Ok(())
}

/// The types, the services' stubs and the kit's sources, written to `dir`.
pub fn write_types(dir: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(dir.join("kit"))?;
    // A module returns one value to be required for its types.
    std::fs::write(dir.join("types.luau"), format!("{}\nreturn {{}}\n", definitions()))?;
    // `./` in a directory's init.luau is the directory's parent: `@self`
    // is the directory.
    let stub = |from: &str, ty: &str| {
        format!("-- Generated by `genoma types`. Do not edit.\nlocal types = require(\"{from}/types\")\nreturn (nil :: any) :: types.{ty}\n")
    };
    std::fs::write(dir.join("init.luau"), stub("@self", "G"))?;
    for (name, ty) in SERVICES {
        std::fs::write(dir.join(format!("{name}.luau")), stub(".", ty))?;
    }
    for (name, source) in kit_modules() {
        std::fs::write(dir.join("kit").join(format!("{name}.luau")), source)?;
    }
    Ok(())
}

/// One `export type` of the API: its comment, and each member with its
/// own.
struct Block {
    name: String,
    doc: Vec<String>,
    /// The type when it is not a table of members.
    alias: Option<String>,
    members: Vec<Member>,
}

struct Member {
    name: String,
    ty: String,
    read_only: bool,
    doc: Vec<String>,
}

fn parse(api: &str) -> Vec<Block> {
    let mut blocks = Vec::new();
    let mut doc: Vec<String> = Vec::new();
    let mut lines = api.lines().peekable();
    while let Some(line) = lines.next() {
        let t = line.trim();
        if let Some(c) = t.strip_prefix("--") {
            let c = c.trim();
            if c.starts_with("----") || c.starts_with("Genoma's Luau API") {
                doc.clear();
            } else {
                doc.push(c.to_owned());
            }
            continue;
        }
        let Some(rest) = t.strip_prefix("export type ") else {
            doc.clear();
            continue;
        };
        let (head, body) = rest.split_once('=').unwrap_or((rest, ""));
        let name = head.trim().to_owned();
        let body = body.trim();
        // A table on one line: { a: x, b: y }.
        if body.starts_with('{') && body.ends_with('}') && body.len() > 2 {
            let members = split_top(&body[1..body.len() - 1])
                .into_iter()
                .filter_map(|m| {
                    let (read_only, m) = match m.strip_prefix("read ") {
                        Some(rest) => (true, rest),
                        None => (false, m.as_str()),
                    };
                    let (n, ty) = m.split_once(':')?;
                    Some(Member { name: n.trim().to_owned(), ty: ty.trim().to_owned(), read_only, doc: Vec::new() })
                })
                .collect();
            blocks.push(Block { name, doc: std::mem::take(&mut doc), alias: None, members });
            continue;
        }
        if !body.ends_with('{') {
            blocks.push(Block { name, doc: std::mem::take(&mut doc), alias: Some(body.to_owned()), members: Vec::new() });
            continue;
        }
        // Members to the closing brace: a member's type may span lines.
        let mut members = Vec::new();
        let mut member_doc: Vec<String> = Vec::new();
        let mut pending = String::new();
        let mut depth = 0i32;
        for line in lines.by_ref() {
            let t = line.trim();
            if depth == 0 && pending.is_empty() {
                if t.starts_with('}') {
                    break;
                }
                if let Some(c) = t.strip_prefix("--") {
                    member_doc.push(c.trim().to_owned());
                    continue;
                }
            }
            if !pending.is_empty() {
                pending.push(' ');
            }
            pending.push_str(t);
            depth += t.matches(['{', '(']).count() as i32 - t.matches(['}', ')']).count() as i32;
            if depth > 0 {
                continue;
            }
            depth = 0;
            let text = std::mem::take(&mut pending).replace(", }", " }").replace(",}", " }");
            let text = text.trim_end_matches(',');
            let (read_only, text) = match text.strip_prefix("read ") {
                Some(rest) => (true, rest),
                None => (false, text),
            };
            if let Some((name, ty)) = text.split_once(':') {
                members.push(Member {
                    name: name.trim().to_owned(),
                    ty: ty.trim().to_owned(),
                    read_only,
                    doc: std::mem::take(&mut member_doc),
                });
            }
            member_doc.clear();
        }
        blocks.push(Block { name, doc: std::mem::take(&mut doc), alias: None, members });
    }
    blocks
}

/// `text` split at its commas outside brackets.
fn split_top(text: &str) -> Vec<String> {
    let mut parts = Vec::new();
    let mut depth = 0i32;
    let mut current = String::new();
    for c in text.chars() {
        match c {
            '{' | '(' | '<' => depth += 1,
            '}' | ')' | '>' => depth -= 1,
            ',' if depth == 0 => {
                parts.push(std::mem::take(&mut current).trim().to_owned());
                continue;
            }
            _ => {}
        }
        current.push(c);
    }
    if !current.trim().is_empty() {
        parts.push(current.trim().to_owned());
    }
    parts
}

/// The names `parse` finds, by type: for the test that keeps them with
/// what the runtime registers.
#[cfg(test)]
pub fn api_members() -> std::collections::HashMap<String, Vec<String>> {
    parse(API)
        .into_iter()
        .map(|b| (b.name.split('<').next().unwrap_or_default().to_owned(), b.members.into_iter().map(|m| m.name).collect()))
        .collect()
}

fn ty_name(ty: Ty) -> String {
    match ty {
        Ty::Number => "number".into(),
        Ty::Color => "colour".into(),
        Ty::Text => "string".into(),
        Ty::Bool => "boolean".into(),
        Ty::Numbers => "{ number }".into(),
        Ty::Stops => "{ { position, colour } }".into(),
        Ty::Runs => "{ run }".into(),
        Ty::Choice(options) => options.iter().map(|o| format!("\"{o}\"")).collect::<Vec<_>>().join(" \\| "),
    }
}

/// `genoma reference`: every node property, every function of `g` and every
/// service, in Markdown.
pub fn reference() -> String {
    let blocks = parse(API);
    let by_name = |n: &str| blocks.iter().find(|b| b.name == n);
    let mut out = String::new();
    let _ = writeln!(out, "# Genoma API reference\n");
    let _ = writeln!(
        out,
        "Generated by `genoma reference` from the node schema and `crates/genoma-script/api.luau`; \
         `genoma types` gives the same as Luau types for luau-lsp. Do not edit: run \
         `genoma reference > docs/reference.md`.\n"
    );
    let _ = writeln!(out, "- [Nodes](#nodes)\n- [Node properties](#node-properties)\n- [Input](#input)\n- [g](#g)");
    for (name, ty) in SERVICES {
        let _ = writeln!(out, "- [@genoma/{name}](#{})", ty.to_lowercase());
    }
    let _ = writeln!(out, "- [Types](#types)\n");

    // Nodes, from g's constructors.
    let _ = writeln!(out, "## Nodes\n");
    if let Some(g) = by_name("G") {
        for m in g.members.iter().filter(|m| m.ty.ends_with("-> Node")) {
            let _ = writeln!(out, "- `g.{}`{}", m.name, if m.doc.is_empty() { String::new() } else { format!(": {}", m.doc.join(" ")) });
        }
    }
    let _ = writeln!(out, "\nEach takes the properties below; a property given a function is a binding, re-run when what it read changes.\n");

    let _ = writeln!(out, "## Node properties\n");
    let _ = writeln!(out, "| Property | Type | Moves | What it does |\n|---|---|---|---|");
    for p in PROPS {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} |",
            p.name,
            ty_name(p.ty),
            if p.animatable { "yes" } else { "" },
            p.doc.replace('|', "\\|")
        );
    }
    let _ = writeln!(out, "\nEvery node also takes `role`, `name` (for assistive technology), `id` (what a popup's anchor or `combine_with` names it by) and `transition` (property → timing name).\n");

    let _ = writeln!(out, "## Input\n");
    // Node's own, before Each and List repeat them.
    for line in genoma_scene::luau_definitions().lines().take_while(|l| !l.starts_with("export type Each")) {
        let t = line.trim();
        if t.starts_with("on_") {
            let (name, ty) = t.trim_end_matches(',').split_once(':').unwrap_or((t, ""));
            let ty = ty.trim();
            let ty = ty.strip_prefix('(').and_then(|t| t.strip_suffix(")?")).unwrap_or(ty);
            let _ = writeln!(out, "- `{name}`: `{ty}`");
        }
    }
    let _ = writeln!(out);

    let member_list = |out: &mut String, prefix: &str, block: &Block| {
        for m in &block.members {
            let call = m.ty.contains("->") && !m.read_only;
            let sep = if call && m.ty.contains("self:") { ":" } else { "." };
            let _ = writeln!(out, "### `{prefix}{sep}{}`\n", m.name);
            let _ = writeln!(out, "```luau\n{}{}: {}\n```\n", if m.read_only { "read " } else { "" }, m.name, m.ty);
            if !m.doc.is_empty() {
                let _ = writeln!(out, "{}\n", m.doc.join(" "));
            }
        }
    };

    let _ = writeln!(out, "## g\n\n`local g = require(\"@genoma\")`\n");
    if let Some(g) = by_name("G") {
        let rest = Block {
            name: String::new(),
            doc: Vec::new(),
            alias: None,
            members: g.members.iter().filter(|m| !m.ty.ends_with("-> Node")).map(|m| Member { name: m.name.clone(), ty: m.ty.clone(), read_only: m.read_only, doc: m.doc.clone() }).collect(),
        };
        member_list(&mut out, "g", &rest);
    }

    for (name, ty) in SERVICES {
        let Some(block) = by_name(ty) else { continue };
        let _ = writeln!(out, "## {ty}\n\n`local {name} = require(\"@genoma/{name}\")`\n");
        let doc: Vec<&String> = block.doc.iter().filter(|d| !d.starts_with('@')).collect();
        if let Some(about) = block.doc.iter().find(|d| d.starts_with('@')) {
            let _ = writeln!(out, "{}\n", about.split_once(':').map_or("", |(_, a)| a.trim()));
        }
        for d in doc {
            let _ = writeln!(out, "{d}\n");
        }
        member_list(&mut out, name, block);
    }

    let _ = writeln!(out, "## Types\n");
    let service_types: Vec<&str> = SERVICES.iter().map(|(_, t)| *t).collect();
    for block in blocks.iter().filter(|b| b.name != "G" && !service_types.contains(&b.name.as_str())) {
        let _ = writeln!(out, "### {}\n", block.name);
        if !block.doc.is_empty() {
            let _ = writeln!(out, "{}\n", block.doc.join(" "));
        }
        match &block.alias {
            Some(alias) => {
                let _ = writeln!(out, "```luau\n{alias}\n```\n");
            }
            None => {
                let _ = writeln!(out, "| Field | Type | |\n|---|---|---|");
                for m in &block.members {
                    let _ = writeln!(out, "| `{}` | `{}` | {} |", m.name, m.ty.replace('|', "\\|"), m.doc.join(" ").replace('|', "\\|"));
                }
                let _ = writeln!(out);
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_api_parses_into_its_types() {
        let blocks = parse(API);
        let g = blocks.iter().find(|b| b.name == "G").expect("G");
        let process = g.members.iter().find(|m| m.name == "process").expect("g.process");
        assert!(process.ty.contains("on_exit") && process.ty.ends_with("-> Process"), "a type over several lines: {}", process.ty);
        let compositor = blocks.iter().find(|b| b.name == "Compositor").unwrap();
        assert!(compositor.members.iter().any(|m| m.name == "name" && m.read_only));
        for (_, ty) in SERVICES {
            assert!(blocks.iter().any(|b| b.name == *ty), "a type for {ty}");
        }
        let text = reference();
        assert!(text.contains("### `compositor:focus_workspace`") && text.contains("| `combine_with` |"));
    }

    /// The reference in the repository is the one the code gives.
    #[test]
    fn the_reference_in_the_repository_is_current() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/reference.md");
        let written = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(written == reference(), "docs/reference.md is stale: run `genoma reference > docs/reference.md`");
    }

    /// Every name the runtime registers, in `g` and on each userdata, is
    /// in the API, under the type it has there.
    #[test]
    fn the_api_names_everything_the_runtime_registers() {
        let members = api_members();
        let types: std::collections::HashMap<&str, &str> = [
            ("ClockRef", "Clock"),
            ("NiriRef", "Niri"),
            ("CompositorRef", "Compositor"),
            ("VitalsRef", "Vitals"),
            ("PowerRef", "Power"),
            ("NetworkRef", "Network"),
            ("MediaRef", "Media"),
            ("AudioRef", "Audio"),
            ("BluetoothRef", "Bluetooth"),
            ("ToplevelsRef", "Toplevels"),
            ("IdleRef", "Idle"),
            ("LockRef", "Lock"),
            ("TrayRef", "Tray"),
            ("PolkitRef", "Polkit"),
            ("NotificationsRef", "Notifications"),
            ("ClipboardRef", "Clipboard"),
            ("AppsRef", "Apps"),
            ("SessionRef", "Session"),
            ("Inhibition", "Inhibition"),
            ("SpectrumRef", "Spectrum"),
            ("SpectrumHold", "SpectrumHold"),
            ("Process", "Process"),
            ("Watched", "WatchedFile"),
            ("Folder", "Folder"),
            ("Socket", "Socket"),
            ("Timer", "Stoppable"),
            ("Watch", "Stoppable"),
            ("Auth", "Auth"),
            ("Greetd", "Greetd"),
            ("Computed", "Computed"),
            ("Animated", "Animated"),
            ("State", "Signal"),
        ]
        .into_iter()
        .collect();
        let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../genoma-script/src");
        let mut missing = Vec::new();
        for entry in std::fs::read_dir(&dir).unwrap() {
            let path = entry.unwrap().path();
            if path.extension().is_none_or(|e| e != "rs") {
                continue;
            }
            let source = std::fs::read_to_string(&path).unwrap();
            let mut owner: Option<&str> = None;
            for line in source.lines() {
                let t = line.trim();
                if let Some(rest) = t.strip_prefix("impl UserData for ").or_else(|| t.strip_prefix("impl mlua::UserData for ")) {
                    let name = rest.split([' ', '{', '<']).next().unwrap_or("");
                    owner = Some(types.get(name).copied().unwrap_or_else(|| panic!("which API type is {name}?")));
                    continue;
                }
                for prefix in ["add_field_method_get(\"", "add_method(\"", "add_method_mut(\""] {
                    if let Some(i) = t.find(prefix) {
                        let name = t[i + prefix.len()..].split('"').next().unwrap();
                        let ty = owner.expect("a member outside a UserData impl");
                        if !members.get(ty).is_some_and(|m| m.iter().any(|n| n == name)) {
                            missing.push(format!("{ty}.{name}"));
                        }
                    }
                }
            }
        }
        // g's own, registered by name or in a loop of names.
        let lib = std::fs::read_to_string(dir.join("lib.rs")).unwrap();
        let g = &members["G"];
        let mut names: Vec<String> = Vec::new();
        let mut rest = lib.as_str();
        while let Some(i) = rest.find("g.set(") {
            rest = &rest[i + 6..];
            let quoted = rest.trim_start();
            if let Some(q) = quoted.strip_prefix('"') {
                names.push(q.split('"').next().unwrap().to_owned());
            }
        }
        for line in lib.lines().filter(|l| l.contains(" in [") && (l.contains("for (name") || l.contains("for kind"))) {
            for part in line.split('"').skip(1).step_by(2) {
                names.push(part.to_owned());
            }
        }
        for name in names {
            if !g.contains(&name) {
                missing.push(format!("g.{name}"));
            }
        }
        // And every service the require answers is one the API types.
        for (name, _) in SERVICES {
            assert!(lib.contains(&format!("\"@genoma/{name}\"")), "@genoma/{name} is required somewhere");
        }
        assert!(missing.is_empty(), "registered but not in api.luau: {missing:?}");
    }
}
